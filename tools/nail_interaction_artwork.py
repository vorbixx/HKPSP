SOURCE = ROOT/'_private/research/nail-interactions'


def door_glyph_advances(font, glyphs, scale):
    point_size=font['m_fontInfo']['PointSize']
    return [((glyphs[code]['xAdvance'] if code in glyphs else point_size*.25)*scale)
            for code in range(32,96)]


def door_glyph_header(advances):
    if len(advances)!=64:
        raise ValueError('Door glyph advance table must cover ASCII 32..95')
    values=',\n'.join('    '+format(value,'.9g')+'f' for value in advances)
    return ('// Generated by tools/nail_interaction_artwork.py from the shared Trajan metrics.\n'
            '#pragma once\nnamespace hk3ds::doorfont {\n'
            f'inline constexpr float advance[64] = {{\n{values}\n}};\n'
            'inline constexpr unsigned first=33;\n'
            'inline constexpr unsigned count=63;\n'
            'inline constexpr float enlargement=1.15f;\n'
            '}\n')


def door_glyph(atlas, glyph, scale, ppu):
    pad=4
    crop=(round(glyph['x'])-pad,round(glyph['y'])-pad,
          round(glyph['x']+glyph['width'])+pad,round(glyph['y']+glyph['height'])+pad)
    mask=atlas.crop(crop).point(lambda value:255 if value>=128 else 0)
    size=(max(1,round(mask.width*scale*ppu)),max(1,round(mask.height*scale*ppu)))
    mask=mask.resize(size,Image.Resampling.LANCZOS)
    padded=Image.new('L',(size[0]+2,size[1]+2))
    padded.paste(mask,(1,1))
    outline=padded.filter(ImageFilter.MaxFilter(3))
    bitmap=Image.new('RGBA',padded.size,(0,0,0,0))
    bitmap.putalpha(outline)
    face=Image.new('RGBA',padded.size,(255,255,255,0))
    face.putalpha(padded)
    bitmap.alpha_composite(face)
    left=(glyph['xOffset']-pad)*scale-1/ppu
    top=(glyph['yOffset']+pad)*scale+1/ppu
    return bitmap,(left,top-bitmap.height/ppu,left+bitmap.width/ppu,top)


def append_interactions(add_sprite, clip, output, romfs, source=SOURCE):
    mapping=json.loads((source/'interaction-map.json').read_text())
    if mapping['build'] != 22529139:
        raise ValueError('Unexpected interaction source build')
    for name, expected in mapping['source_sha256'].items():
        if hashlib.sha256((source/name).read_bytes()).hexdigest()!=expected:
            raise ValueError('Interaction source changed: '+name)
    read=lambda name:json.loads((source/name).read_text())
    library=read('resources.assets-21298.json')['m_Structure']['clips']
    prompt_library=read('resources.assets-23333.json')['m_Structure']['clips']
    source_clips={}
    for name, animation in [('Nail Tink',next(c for c in library if c['name']=='Block')),
                            ('Inspect Up',next(c for c in prompt_library if c['name']=='Up')),
                            ('Inspect Down',next(c for c in prompt_library if c['name']=='Down'))]:
        keys=[]
        for frame in animation['frames']:
            collection=f"resources.assets-{frame['spriteCollection']['m_PathID']}.json"
            definition=read(collection)['m_Structure']['spriteDefinitions'][frame['spriteId']]
            texture=Image.open(source/mapping['textures'][collection]).convert('RGBA')
            bitmap,geometry=decode_sprite(texture,definition)
            # Match the existing prompt adapter's quarter-resolution UI art;
            # geometry remains in original world units.
            reduction=.5 if name=='Nail Tink' else .25
            bitmap=bitmap.convert('RGBa').resize((max(1,math.ceil(bitmap.width*reduction)),max(1,math.ceil(bitmap.height*reduction))),Image.Resampling.BOX).convert('RGBA')
            keys.append(add_sprite(f"interaction/{collection}/{frame['spriteId']}",(bitmap,geometry),half=False))
        clip(name,keys,animation['fps'],animation['wrapMode'],animation['loopStart'])
        source_clips[name]=dict(fps=animation['fps'],frames=[f['spriteId'] for f in animation['frames']],loop=animation['loopStart'])
    # Bake the source Trajan Pro SDF face at its midpoint, as the existing HUD
    # adapter does for Perpetua. TMP's perspective world text uses a .1 scale.
    parts=mapping['trees']['Arrow Prompt/Labels/Inspect']
    text=read(parts['TextMeshPro'][0])['m_Structure']
    font=read(mapping['font']['data'])['m_Structure']
    font_atlas=Image.open(source/mapping['font']['atlas']).getchannel('A')
    glyphs={g['id']:g for g in font['m_glyphInfoList']}
    scale=text['m_fontSize']/font['m_fontInfo']['PointSize']*.1
    word='INSPECT'
    width=sum(glyphs[ord(c)]['xAdvance'] for c in word)*scale
    ppu=64
    left=-width/2;bottom=-.2;top=.8
    label=Image.new('RGBA',(math.ceil(width*ppu)+8,math.ceil((top-bottom)*ppu)))
    x=left
    for c in word:
        g=glyphs[ord(c)];pad=4
        mask=font_atlas.crop((round(g['x'])-pad,round(g['y'])-pad,round(g['x']+g['width'])+pad,round(g['y']+g['height'])+pad)).point(lambda v:255 if v>=128 else 0)
        size=(max(1,round(mask.width*scale*ppu)),max(1,round(mask.height*scale*ppu)))
        mask=mask.resize(size,Image.Resampling.LANCZOS)
        glyph=Image.new('RGBA',size,'white');glyph.putalpha(mask)
        label.alpha_composite(glyph,(round((x+(g['xOffset']-pad)*scale-left)*ppu)+4,round((top-(g['yOffset']+pad)*scale)*ppu)))
        x+=g['xAdvance']*scale
    label=label.resize((max(1,label.width//4),max(1,label.height//4)),Image.Resampling.LANCZOS)
    key=add_sprite('Inspect Label',(label,(left-4/ppu,bottom,left-4/ppu+(label.width*4)/ppu,top)),half=False)
    clip('Inspect Label',[key])

    advances=door_glyph_advances(font,glyphs,scale)
    door_ppu=16*1.15
    door_keys=[]
    for code in range(33,96):
        if code not in glyphs:
            raise ValueError(f'Missing Trajan glyph for ASCII {code}')
        key=add_sprite(f'door-glyph/{code}',door_glyph(font_atlas,glyphs[code],scale,door_ppu),half=False)
        door_keys.append(key)
    clip('Door Glyphs',door_keys)
    generated=door_glyph_header(advances)
    header=ROOT/'include/door_prompt_glyphs.hpp'
    if not header.exists() or header.read_text()!=generated:
        header.write_text(generated,encoding='utf-8',newline='\n')

    shadow=mapping['trees']['Arrow Prompt/Shadow']
    renderer=read(shadow['SpriteRenderer'][0]);sprite=f"resources.assets-{renderer['m_Sprite']['m_PathID']}.json"
    bitmap,geometry=decode(Image.open(source/mapping['sprites'][sprite]).convert('RGBA'),read(sprite))
    bitmap=bitmap.resize((max(1,bitmap.width//4),max(1,bitmap.height//4)),Image.Resampling.LANCZOS)
    tr=read(shadow['Transform'][0]);sx=tr['m_LocalScale']['m_X'];sy=tr['m_LocalScale']['m_Y'];dx=tr['m_LocalPosition']['m_X'];dy=tr['m_LocalPosition']['m_Y']
    geometry=(geometry[0]*sx+dx,geometry[1]*sy+dy,geometry[2]*sx+dx,geometry[3]*sy+dy)
    color=renderer['m_Color'];key=add_sprite('Inspect Shadow',(bitmap,geometry),tuple(color['m_'+c] for c in 'RGBA'),half=False)
    clip('Inspect Shadow',[key])

    def scene(i):return read(f'level6-{i}.json')
    def transform(owner):
        return next(scene(c['m_Component']['m_PathID']) for c in scene(owner)['m_Components'] if 'm_LocalPosition' in scene(c['m_Component']['m_PathID']))
    def chain(t):
        result=[t]
        while t['m_Father']['m_PathID']:
            t=scene(t['m_Father']['m_PathID']);result.append(t)
        return result
    spikes=[];payload=bytearray(b'NIF1')
    for owner in (335,1361):
        boxes=[scene(c['m_Component']['m_PathID']) for c in scene(owner)['m_Components'] if 'm_Size' in scene(c['m_Component']['m_PathID']) and 'm_IsTrigger' in scene(c['m_Component']['m_PathID'])]
        bounds=[]
        for box in boxes:
            pts=[transform_point(p,chain(transform(owner))) for path in paths(box,'BoxCollider2D') for p in path]
            bounds.append([min(p[0] for p in pts),min(p[1] for p in pts),max(p[0] for p in pts),max(p[1] for p in pts)])
        scale=read('resources.assets-9263.json')['m_LocalScale']['m_X']
        payload+=struct.pack('<2If8f',owner,len(bounds),scale,*(bounds+[bounds[0]])[:2][0],*(bounds+[bounds[0]])[:2][1])
        spikes.append(dict(owner=owner,bounds=bounds,scale=scale))
    prompts=[]
    for owner,name in mapping['markers'].items():
        position,scale=world_transform(chain(read(name)))
        payload+=struct.pack('<I3f',int(owner),*position)
        prompts.append(dict(owner=int(owner),position=position))
    for directory in (output,romfs):(directory/'nail-interactions.bin').write_bytes(payload)
    return dict(source_sha256=mapping['source_sha256'],spikes=spikes,prompts=prompts,clips=source_clips,
                font=read(mapping['font']['data'])['m_Name'],font_size=text['m_fontSize'],
                approximation='SDF face midpoint rasterized; TMP label vertical layout approximated')
