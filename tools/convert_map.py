"""Pack supported scenes' original map ink into a 128 KiB lower-LCD atlas."""
import converted_files  # Install hardlink copy-on-write before asset writes.
import argparse
import hashlib
import json
import shutil
import tex3ds_cache
from pathlib import Path
from private_output_paths import is_private_output

from PIL import Image
from assetripper_client import ROOT
from atlas_packing import pack_pages
from convert_room_visuals import decode
from convert_scenes import SCENES
from text_raster import sdf_glyph
from tool_paths import TEX3DS as TEX3DS_EXE

PIXELS_PER_UNIT = 48
PAGE_SIZE = (512, 512)


def convert(source, output, romfs, tex3ds):
    for path in (output, romfs):
        if not converted_files.private_output(path, ROOT):
            raise ValueError('Converted assets must remain private')
        path.mkdir(parents=True, exist_ok=True)
    mapping = json.loads((source / 'map.json').read_text())
    for name, expected in mapping['source_sha256'].items():
        if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
            raise ValueError('Map source hash mismatch: ' + name)
    read = lambda name: json.loads((source / name).read_text())
    atlases = {}
    images, entries = [], []

    def add(entry, scale=PIXELS_PER_UNIT, transform_scale=(1, 1)):
        sprite = read(entry['sprite'])
        texture = entry['texture']
        if texture not in atlases:
            atlases[texture] = Image.open(source / texture).convert('RGBA')
        bitmap, bounds = decode(atlases[texture], sprite)
        size = tuple(max(1, round(v * scale * s / sprite['m_PixelsToUnits'])) for v, s in zip(bitmap.size, transform_scale))
        bounds = tuple(v * transform_scale[i % 2] for i, v in enumerate(bounds))
        bitmap = bitmap.convert('RGBa').resize(size, Image.Resampling.LANCZOS).convert('RGBA')
        index = len(images)
        images.append((index, bitmap, bounds))
        return index

    marker = add(mapping['marker'], 22)
    for room in mapping['rooms']:
        if room['id'] not in (*SCENES, 'Tutorial_01'):
            continue
        t = read(room['transform'])
        scale = [t['m_LocalScale'][f'm_{a}'] for a in 'XY']
        pos = [t['m_LocalPosition'][f'm_{a}'] + room['parent'][f'm_{a}'] for a in 'XY']
        sprite = read(room['sprite'])
        size = [sprite['m_Rect'][f'm_{a}'] / sprite['m_PixelsToUnits'] * scale[i] for i, a in enumerate(('Width', 'Height'))]
        color = [round(room['color'][f'm_{a}'] * 255) for a in 'RGBA']
        full_image = add(room, transform_scale=scale)
        rough_image = add(room['rough'], transform_scale=scale) if room.get('rough') else 0xffffffff
        entries.append(dict(id=room['id'], area=0 if room['area'] == 'Dirtmouth' else 1,
                            image=full_image, rough=rough_image, position=pos, size=size, color=color))
        for pin in room['pins']:
            pt = read(pin['transform'])
            # Pin sizes are a readability approximation; source placement/art retained.
            pi = add(pin, 24)
            entries[-1].setdefault('pins', []).append(dict(image=pi, position=[
                pos[i] + pt['m_LocalPosition'][f'm_{a}'] * scale[i] for i, a in enumerate('XY')]))

    # Bake area names from the original Perpetua face at LCD resolution.
    font_source = ROOT / '_private/research/tutorial-reminders'
    fm = json.loads((font_source / 'prompt-map.json').read_text())
    font = fm['fonts']['sharedassets0.assets-194.json']
    font_atlas = Image.open(font_source / 'sharedassets0.assets-41.png').getchannel('A')
    glyphs = {g['id']: g for g in font['m_glyphInfoList']}
    labels = []
    for text in ("DIRTMOUTH", 'FORGOTTEN CROSSROADS', "KING'S PASS", 'UNCHARTED'):
        label = Image.new('RGBA', (300, 25))
        x = 0
        for char in text:
            if char == ' ':
                x += 4
                continue
            g = glyphs[ord(char)]
            bitmap, b = sdf_glyph(font_atlas, g, font, 15)
            label.alpha_composite(bitmap, (round(x + b[0] * 16), round(18 - b[3] * 16)))
            x += g['xAdvance'] * 15 / font['m_fontInfo']['PointSize']
        label = label.crop((0, 0, min(300, round(x) + 2), 25))
        labels.append(len(images))
        images.append((len(images), label, (0, 0, label.width, label.height)))
    records, pages = pack_pages(images, (PAGE_SIZE,))
    png, texture = output / 'map-page-0.png', output / 'map-page-0.t3x'
    pages[0].save(png)
    # Four-bit ink/alpha retain LCD geometry while sharing memory with inventory.
    tex3ds_cache.run([str(tex3ds), '-f', 'la4', '-z', 'none', '-o', str(texture), str(png)], check=True)
    shutil.copyfile(texture, romfs / texture.name)
    floats = lambda seq: ','.join(f'{v:.7f}f' for v in seq)
    lines = ['// Generated by tools/convert_map.py from build 22529139; do not edit.',
             '#pragma once', '#include <cstddef>', 'namespace hk3ds::mapdata {',
             'struct Image { unsigned x,y,w,h; float left,bottom,right,top; };',
             'struct Room { const char* id; unsigned image,rough,area; float x,y,w,h; unsigned char r,g,b,a; };',
             'struct Pin { unsigned room,image; float x,y; };',
             'inline constexpr Image images[]={']
    for index in range(len(images)):
        page, x, y, w, h, *bounds = records[index]
        lines.append('{' + ','.join(map(str, (x, y, w, h))) + ',' + floats(bounds) + '},')
    lines += ['};', 'inline constexpr Room rooms[]={']
    for r in entries:
        lines.append('{"' + r['id'] + '",' + f'{r["image"]},{r["rough"]},{r["area"]},' +
                     floats(r['position'] + r['size']) + ',' + ','.join(map(str, r['color'])) + '},')
    lines += ['};', 'inline constexpr std::size_t roomCount=sizeof(rooms)/sizeof(rooms[0]);',
              'inline constexpr Pin pins[]={']
    for i, r in enumerate(entries):
        for p in r.get('pins', []):
            lines.append('{' + f'{i},{p["image"]},' + floats(p['position']) + '},')
    lines += ['};', f'inline constexpr unsigned marker={marker};',
              'inline constexpr unsigned labels[]={' + ','.join(map(str, labels)) + '};',
              f'inline constexpr float pixelsPerUnit={PIXELS_PER_UNIT}.f;',
              f'inline constexpr std::size_t textureBytes={PAGE_SIZE[0]}*{PAGE_SIZE[1]};', '}']
    header = ROOT / 'include/map_data.hpp'
    content = '\n'.join(lines) + '\n'
    if not header.exists() or header.read_text() != content:
        header.write_text(content, encoding='utf-8', newline='\n')
    manifest = dict(build_id=mapping['build_id'], texture_bytes=PAGE_SIZE[0]*PAGE_SIZE[1],
                    texture_format='la4', pages=1, page_size=list(PAGE_SIZE), rooms=entries,
                    rough_rooms=sum(r['rough'] != 0xffffffff for r in entries))
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(f'Map: {len(entries)} source rooms, {sum(r["rough"] != 0xffffffff for r in entries)} authored rough rooms; 128 KiB LA4 atlas')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / '_private/research/bottom-map')
    parser.add_argument('--output', type=Path, default=ROOT / '_private/converted/map')
    parser.add_argument('--romfs', type=Path, default=ROOT / '_private/converted/hero/romfs')
    parser.add_argument('--tex3ds', type=Path, default=Path(TEX3DS_EXE))
    args = parser.parse_args()
    convert(args.source, args.output, args.romfs, args.tex3ds)
