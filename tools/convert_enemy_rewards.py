"""Derive ordinary enemy payouts from saved copied-build component exports.

Does not extract art or change the save schema. Writes only this checkout's
small source table and private provenance manifest.
"""
import converted_files  # Install hardlink copy-on-write before asset writes.
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def convert(output):
    research = ROOT / '_private/research'
    hashes, result = {}, []

    def read(path):
        raw = path.read_bytes()
        hashes[path.relative_to(ROOT).as_posix()] = hashlib.sha256(raw).hexdigest()
        return json.loads(raw)

    def components(entry, kind):
        if isinstance(entry, dict):
            if kind in entry:
                return entry[kind]
            for value in entry.values():
                found = components(value, kind)
                if found:
                    return found
        return []

    def append(name, health, persistent):
        p = health.get('effectOrigin', dict(x=0, y=0))
        result.append(dict(name=name, small=health.get('smallGeoDrops', 0),
                           medium=health.get('mediumGeoDrops', 0), large=health.get('largeGeoDrops', 0),
                           origin=[p['x'], p['y']], persistent=persistent is not None,
                           semiPersistent=bool(persistent and persistent['semiPersistent']),
                           megaFling=bool(health.get('megaFlingGeo', False))))

    def mapped(name, directory, filename, select=lambda m: m):
        source = research / directory
        mapping = read(source / filename)
        entry = select(mapping)

        def component(kind):
            paths = components(entry, kind)
            if not paths:
                return None
            path = source / paths[0]
            raw = read(path)
            expected = mapping.get('source_sha256', {}).get(paths[0])
            if expected and hashes[path.relative_to(ROOT).as_posix()] != expected:
                raise ValueError('Changed original component ' + str(path))
            return raw.get('m_Structure', raw)

        health = component('HealthManager')
        if health is None and name != 'Goam':
            raise ValueError('Missing original HealthManager for ' + name)
        append(name, health or {}, component('PersistentBoolItem'))

    mapped('Crawler', 'enemy', 'crawler-map.json', lambda m: m['actor'])
    for name, stem in [('Tiktik','tiktik'), ('Gruzzer','gruzzer')]:
        mapped(name, 'crossroads-enemies-a', stem+'-map.json', lambda m: m['actor'])
    mapped('Vengefly', 'tutorial', 'inventory.json',
           lambda m: next(r for r in m['rows'] if r['collider'] == 'level6-8285.json'))
    mapped('Hatchling', 'crossroads-enemies-a', 'aspid-hatchling-map.json', lambda m: m['actor'])
    for name, key in [('Wandering','wandering_husk'), ('Hornhead','husk_hornhead'),
                      ('Leaping','leaping_husk'), ('Goam','goam')]:
        mapped(name, 'crossroads-enemies-b', 'enemies-map.json', lambda m, k=key: m[k])
    mapped('Bully', 'crossroads-enemies-c', 'enemies-map.json', lambda m: m['actors']['husk_bully_candidate'])
    # The old Baldur candidate is only an animation library. Use a live Roller.
    mapped('Baldur', 'crossroads-scenes/Crossroads_ShamanTemple/terrain', 'terrain-map.json',
           lambda m: next(parts for row in m['inventory'] for owner, parts in zip(row['owners'], row['components'])
                          if owner == 'level76-2109.json'))
    mapped('Mother', 'crossroads-enemies-c', 'enemies-map.json', lambda m: m['actors']['hatcher_actor'])
    # Saved with the Greenpath snapshot (convert_greenpath_enemies.py --extract).
    rows = read(ROOT / '_private/converted/greenpath-enemies-source/source-components.json')
    for name, prefab in [('Mosscreep','Moss Walker'), ('Maskfly','Pigeon'), ('MossKnight','Moss Knight'),
                         ('Squit','Mosquito'), ('Aluba','Lazy Flyer Enemy'), ('Durandoo','Acid Walker'),
                         ('VolatileMosskin','Mossman_Shaker'), ('MossCharger','Moss Charger')]:
        own = [r for r in rows if r['actor'] == prefab and 'data' in r]
        health = next(r['data'] for r in own if 'smallGeoDrops' in r['data'])
        persistent = next((r['data'] for r in own if 'persistentBoolData' in r['data']), None)
        append(name, health, persistent)

    lines = ['// Generated by tools/convert_enemy_rewards.py; copied Steam build 22529139.',
             'const EnemyRewardConfig profiles[]={']
    for row in result:
        x, y = row['origin']
        lines.append('    {%d,%d,%d,{%.8ff,%.8ff},%s,%s,%s}, // %s' % (
            row['small'], row['medium'], row['large'], x, y,
            str(row['persistent']).lower(), str(row['semiPersistent']).lower(),
            str(row['megaFling']).lower(), row['name']))
    lines.append('};')
    (ROOT / 'include/enemy_reward_data.hpp').write_text(
        '\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
    output.mkdir(parents=True, exist_ok=True)
    (output / 'manifest.json').write_text(json.dumps(dict(build_id=22529139, enemies=result, source_sha256=hashes), indent=2)+'\n')
    print(json.dumps(result))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'_private/converted/enemy-rewards')
    convert(parser.parse_args().output)
