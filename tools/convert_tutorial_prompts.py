"""Reuse the HUD page for original Perpetua SDF glyphs and Focus artwork."""
import converted_files  # Install hardlink copy-on-write before asset writes.
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw
from convert_room_visuals import decode
from text_raster import PROMPT_SCALES, sdf_glyph
from top_screen_ui_layout import LAYOUT

ROOT = Path(__file__).resolve().parents[1]


def append_prompts(source, static, extra_characters=(), *, write_metrics=True):
    mapping = json.loads((source / 'prompt-map.json').read_text())
    for filename, expected in mapping['source_sha256'].items():
        if hashlib.sha256((source / filename).read_bytes()).hexdigest() != expected:
            raise ValueError('Prompt source hash mismatch: ' + filename)
    font = mapping['fonts']['sharedassets0.assets-194.json']
    atlas = Image.open(source / 'sharedassets0.assets-41.png').convert('RGBA').getchannel('A')
    glyphs = {g['id']: g for g in font['m_glyphInfoList']}
    size = 16
    scale = size / font['m_fontInfo']['PointSize']
    advances = []
    for code in range(32, 127):
        g = glyphs.get(code)
        if code == 32:
            # TMP synthesizes the absent whitespace glyph from the point size.
            g = dict(xAdvance=font['m_fontInfo']['PointSize']/4)
        if g is None:
            raise ValueError(f'Missing original prompt glyph {code}')
        advances.append(g['xAdvance'] * scale)
        for index, final_scale in enumerate(PROMPT_SCALES):
            if code == 32:
                bitmap, geometry = Image.new('RGBA', (1, 1)), (0, -1/16, 1/16, 0)
            else:
                bitmap, geometry = sdf_glyph(atlas, g, font, size*final_scale,
                                             raster_scale=LAYOUT['panelScale'])
            static(f'LCD Glyph {index} {code}', ('lcd-glyph', index, code), bitmap, geometry)
    for name, key in [('Prompt Backboard', 'resources.assets-1803.json'),
                      ('Focus Panel', 'sharedassets6.assets-271.json')]:
        sprite = json.loads((source / key).read_text())
        texture = Image.open(source / mapping['sprites'][key]).convert('RGBA')
        bitmap, geometry = decode(texture, sprite)
        # Focus now occupies ~186 LCD ink pixels. Keep enough source samples
        # for that size; the old 1/8 bitmap magnified into visible blocks.
        reduction = .5 if name == 'Focus Panel' else .25
        bitmap = bitmap.resize((max(1, round(bitmap.width*reduction)), max(1, round(bitmap.height*reduction))), Image.Resampling.LANCZOS)
        static(name, ('prompt-art', name), bitmap, geometry)
    # Mapped 3DS face buttons use a transparent antialiased ring. Two filled
    # circles leave an opaque black disk, or a white disk at partial alpha.
    ring = Image.new('RGBA', (192, 192))
    draw = ImageDraw.Draw(ring)
    draw.ellipse((16, 16, 175, 175), fill='white')
    draw.ellipse((32, 32, 159, 159), fill=(0, 0, 0, 0))
    ring = ring.resize((24, 24), Image.Resampling.LANCZOS)
    static('Prompt Button', ('prompt-button', 0), ring, (-.75, -.75, .75, .75))
    generated = '// Generated by tools/convert_tutorial_prompts.py from source Perpetua metrics.\n#pragma once\nnamespace hk3ds::promptdata {\n'
    generated += 'inline constexpr float glyphAdvance[95] = {\n'
    generated += ','.join(f'{v:.7f}f' for v in advances) + '};\n'
    generated += 'inline constexpr float lcdScales[] = {' + ','.join(f'{v}f' for v in PROMPT_SCALES) + '};\n}\n'
    header = ROOT / 'include/tutorial_prompt_glyphs.hpp'
    if write_metrics and (not header.exists() or header.read_text() != generated):
        header.write_text(generated, encoding='utf-8', newline='\n')
    return dict(source_sha256=mapping['source_sha256'], font='Perpetua', glyph_pixels=size,
                approximation='SDF face midpoint baked and downsampled; 3DS button glyphs')
