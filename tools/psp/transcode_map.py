"""Convert the existing Crossroads map atlas to a PSP CLUT8 page."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import transcode_room as room

REGIONS = ('Greenpath', 'Fungal Wastes', 'Ancient Basin', 'Deepnest')


def regional(source, output, Image):
    sys.path.insert(0, str(room.REPO / 'tools'))
    from convert_room_visuals import decode
    import hashlib

    mapping = json.loads((source / 'map.json').read_text(encoding='utf-8'))
    for name, expected in mapping['source_sha256'].items():
        if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
            raise ValueError('Map source hash mismatch: ' + name)
    read = lambda name: json.loads((source / name).read_text(encoding='utf-8'))
    textures, images, entries = {}, [], []

    def add(entry, scale):
        sprite = read(entry['sprite'])
        texture = entry['texture']
        if texture not in textures:
            with Image.open(source / texture) as original:
                textures[texture] = original.convert('RGBA')
        ink, bounds = decode(textures[texture], sprite)
        bounds = tuple(value * scale[index % 2] for index, value in enumerate(bounds))
        size = tuple(max(1, round(20 * (bounds[index + 2] - bounds[index]))) for index in range(2))
        images.append((ink.convert('RGBa').resize(size, Image.Resampling.LANCZOS).convert('RGBA'), bounds))
        return len(images) - 1

    for entry in sorted(mapping['rooms'], key=lambda entry: (REGIONS.index(entry['area']), entry['id'])):
        transform = read(entry['transform'])
        scale = [transform['m_LocalScale'][f'm_{axis}'] for axis in 'XY']
        position = [transform['m_LocalPosition'][f'm_{axis}'] + entry['parent'][f'm_{axis}'] for axis in 'XY']
        sprite = read(entry['sprite'])
        dimensions = [sprite['m_Rect'][f'm_{axis}'] * scale[index] / sprite['m_PixelsToUnits']
                      for index, axis in enumerate(('Width', 'Height'))]
        full = add(entry, scale)
        rough = add(entry['rough'], scale) if entry['rough'] else 0xffffffff
        color = [round(entry['color'][f'm_{axis}'] * 255) for axis in 'RGBA']
        entries.append((entry['id'], full, rough, REGIONS.index(entry['area']) + 2, position + dimensions, color))

    placements, page_count = room.pack([ink.size for ink, _ in images], page=512, pad=1)
    if page_count != 1:
        raise ValueError('Regional map art exceeds one transient page')
    atlas = Image.new('RGBA', (512, 512))
    floats = lambda values: ','.join(f'{value:.7f}f' for value in values)
    header = ['// Generated by tools/psp/transcode_map.py from build 22529139; do not edit.',
              '#pragma once', '#include "map_data.hpp"', 'namespace hk3ds::regionalmap {',
              'inline constexpr mapdata::Image images[]={']
    for (ink, bounds), (_, left, top) in zip(images, placements):
        atlas.paste(ink, (left, top))
        header.append(f'{{{left},{top},{ink.width},{ink.height},{floats(bounds)}}},')
    header += ['};', 'inline constexpr mapdata::Room rooms[]={']
    for name, full, rough, area, geometry, color in entries:
        header.append(f'{{"{name}",{full},{rough}u,{area},{floats(geometry)},{",".join(map(str, color))}}},')
    header += ['};', 'inline constexpr std::size_t roomCount=sizeof(rooms)/sizeof(rooms[0]);', '}']
    page = room.quantize_page(Image, atlas)
    (output / 'map-regions.hpt').write_bytes(room.hpt1(*atlas.size, bytes(page.getpalette('RGBA')), page.tobytes()))
    content = '\n'.join(header) + '\n'
    header_path = room.REPO / 'include/map_regional_data.hpp'
    if not header_path.exists() or header_path.read_text(encoding='utf-8') != content:
        header_path.write_text(content, encoding='utf-8', newline='\n')
    return len(entries)


def add_widgets(source, Image, page):
    sys.path.insert(0, str(source / '_private/tools/boss-python'))
    try:
        import UnityPy
    finally:
        sys.path.pop(0)
    archive = source / '_private/original/Hollow Knight/hollow_knight_Data/resources.assets'
    sprites = {obj.path_id: obj for obj in UnityPy.load(str(archive)).objects
               if obj.type.name == 'Sprite' and obj.path_id in (3233, 3326)}
    backboard, arrow = (sprites[path_id].read() for path_id in (3233, 3326))
    if (backboard.m_Name, arrow.m_Name) != ('pop_up_backboard', 'map_arrow'):
        raise ValueError('Unexpected original map UI sprites')
    backboard = backboard.image.convert('RGBA')
    arrow_up = arrow.image.convert('RGBA').resize((15, 7), Image.Resampling.LANCZOS)
    widgets = (
        (0, 336, backboard.resize((204, 60), Image.Resampling.LANCZOS)),
        (208, 336, backboard.resize((138, 36), Image.Resampling.LANCZOS)),
        (350, 336, arrow_up),
        (369, 336, arrow_up.transpose(Image.Transpose.ROTATE_180)),
        (388, 336, arrow_up.transpose(Image.Transpose.ROTATE_90)),
        (399, 336, arrow_up.transpose(Image.Transpose.ROTATE_270)),
    )
    for left, top, sprite in widgets:
        if page.crop((left, top, left + sprite.width, top + sprite.height)).getchannel('A').getbbox():
            raise ValueError('Map widget overlaps the room atlas')
        page.paste(sprite, (left, top))


def convert(source: Path, output: Path) -> dict:
    package = source / '_private/converted/map'
    manifest = json.loads((package / 'manifest.json').read_text(encoding='utf-8'))
    if manifest['pages'] != 1 or manifest['page_size'] != [512, 512]:
        raise ValueError('Expected one 512 x 512 source map page')
    Image = room.import_pil()
    with Image.open(package / 'map-page-0.png') as source_image:
        image = source_image.convert('RGBA')
    if image.size != (512, 512):
        raise ValueError('Map atlas extent no longer matches map_data.hpp')
    add_widgets(source, Image, image)
    page = room.quantize_page(Image, image)
    data = room.hpt1(*image.size, bytes(page.getpalette('RGBA')), page.tobytes())
    output.mkdir(parents=True, exist_ok=True)
    (output / 'map-page-0.hpt').write_bytes(data)
    return {'texture_bytes': len(data), 'rooms': len(manifest['rooms'])}


if __name__ == '__main__':
    output = room.REPO / '_private/converted-psp/map'
    report = convert(room.source_root(), output)
    count = regional(room.REPO / '_private/npc-regional-map', output, room.import_pil())
    print(f"Map: {report['rooms']} Crossroads records, {count} regional records, two CLUT8 pages")
