"""Lower-LCD adaptation of the shared original dialogue composition."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAYOUT = dict(left=20, width=280, scale=.95, baseline=116, lineHeight=15,
              # Source Arrow/Stop x=.11/.08, y=-2.795; bottom fleur y=-2.73.
              center=160, top=94, bottom=195, markerX=161.5, markerY=196,
              controls=222)


def wrap_page(value, advances):
    # Keep authored verse/paragraph breaks; only reflow within each paragraph.
    value = value.replace('<br>', '\n').replace('’', "'").replace('“', '"').replace('”', '"')
    lines = []
    for paragraph in value.strip().split('\n'):
        line = ''
        for word in paragraph.split():
            candidate = (line + ' ' + word).strip()
            if line and sum(advances[ord(c)] for c in candidate) * LAYOUT['scale'] > LAYOUT['width']:
                lines.append(line)
                line = word
            else:
                line = candidate
        lines.append(line)
    if len(lines) > 5 or any(sum(advances[ord(c)] for c in line) * LAYOUT['scale'] > LAYOUT['width'] for line in lines):
        raise ValueError('Mushroom dialogue exceeds its lower-LCD body area')
    return '\n'.join(lines)


def write_header():
    text = '// Generated by tools/convert_conditional_events.py.\n#pragma once\nnamespace hk3ds::dialoguedata {\n'
    text += ''.join(f'inline constexpr float {key}={float(value)}f;\n' for key, value in LAYOUT.items())
    (ROOT / 'include/mushroom_dialogue_data.hpp').write_text(text + '}\n', newline='\n')
