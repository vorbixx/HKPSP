"""Generate Watcher combat constants from the private saved scene export.

Run export_watcher_source.py explicitly first. No original process or extraction
service is started by this converter. Missing/ambiguous authored values fail.
"""
import converted_files  # Install copy-on-write protection before output writes.
import argparse
import json
from pathlib import Path
from watcher_battle import component_data, find_components, state_action


def convert(directory):
    source = json.loads((directory / 'watcher-boss-source.json').read_text())
    transforms = json.loads((directory / 'watcher-boss-transforms.json').read_text())
    actors = {a['name']: a for a in source['actors'] if a['name'].startswith('Black Knight ')
              or a['name'] in ('Battle Control', 'Battle Gate', 'Battle Gate (1)')}
    knight = actors['Black Knight 1']
    def one(actor, kind):
        values = find_components(actor, kind)
        if len(values) != 1:
            raise ValueError(f'Expected one {kind} in {actor["name"]}')
        return component_data(values[0])
    def fsm(actor, name):
        values = [c['decoded'] for c in actor['components']
                  if 'decoded' in c and c['decoded']['name'] == name]
        if len(values) != 1:
            raise ValueError(f'Expected one {name} FSM')
        return values[0]
    control = fsm(knight, 'Black Knight')
    battle = fsm(actors['Battle Control'], 'Battle Control')
    def literal(value):
        if not isinstance(value, dict):
            return value
        if value.get('useVariable') or 'variable' in value:
            raise ValueError(f'Expected authored literal: {value}')
        return value['value']
    def param(f, state, action, key):
        return literal(state_action(f, state, action)[key])
    def variables(f, group):
        return {a['name']: a['value'] for a in f['variables'][group + 'Variables']}
    scalars = variables(control, 'float')
    hp = variables(fsm(knight, 'FSM'), 'int')
    go_transform = {t['m_GameObject']['m_PathID']: int(k) for k, t in transforms.items()}
    def world(key):
        t = transforms[str(key)]
        p, s = t['m_LocalPosition'], t['m_LocalScale']
        parent = t['m_Father']['m_PathID']
        if parent:
            x, y, sx, sy = world(parent)
            return x + p['x'] * sx, y + p['y'] * sy, sx * s['x'], sy * s['y']
        return p['x'], p['y'], s['x'], s['y']
    def rectangle(box, pose=(0, 0, 1, 1)):
        x, y, sx, sy = pose
        o, size = box['m_Offset'], box['m_Size']
        xx = [x + (o['x'] + sign * size['x'] / 2) * sx for sign in (-1, 1)]
        yy = [y + (o['y'] + sign * size['y'] / 2) * sy for sign in (-1, 1)]
        return min(xx), min(yy), max(xx), max(yy)
    def child(name):
        values = [a for a in source['actors'] if a['name'] == name and
                  transforms[str(go_transform[a['path_id']])]['m_Father']['m_PathID'] == go_transform[knight['path_id']]]
        if len(values) != 1:
            raise ValueError(f'Expected one first-knight child {name}')
        return values[0]
    def floats(values):
        return ','.join(f'{v:.9f}f' for v in values)
    lines = ['// Generated by tools/convert_watcher_knights.py; copied original build '+str(source['build_id'])+'.',
             '#pragma once', '#include "physics.hpp"', 'namespace hk3ds::watcher_data {']
    def number(name, value):
        lines.append(f'inline constexpr float {name}={float(value):.9f}f;')
    def rect(name, values):
        lines.append(f'inline constexpr Rect {name}{{{floats(values)}}};')
    lines.append('inline constexpr int hpByNail[]={'+','.join(str(hp[f'Level {i}']) for i in range(1,6))+'};')
    number('chargeSpeed', scalars['Charge Speed']); number('runSpeed', scalars['Run Speed'])
    number('slashSpeed', scalars['Slash Speed'])
    number('runModifyMin',param(control,'Start Run','RandomFloat','min'))
    number('runModifyMax',param(control,'Start Run','RandomFloat','max'))
    run_state=next(s for s in control['states'] if s['name']=='Run To')
    waits=[a['parameters'] for a in run_state['actions'] if a['enabled'] and a['type'].split(',')[0].endswith('.WaitRandom')]
    if len(waits)!=2 or any((literal(w['timeMin']),literal(w['timeMax']))!=(literal(waits[0]['timeMin']),literal(waits[0]['timeMax'])) for w in waits):
        raise ValueError('Expected two matching authored Run To waits')
    number('runWaitMin',literal(waits[0]['timeMin'])); number('runWaitMax',literal(waits[0]['timeMax']))
    for name,state in (('moveWeights','Move Choice'),('closeWeights','In Range Choice'),('multiWeights','In Range Double')):
        action=state_action(control,state,'SendRandomEventV2')
        weights=[literal(w) for w in action['weights']['elements']]
        if action['events']['elements']!=['CHARGE ROLL','JUMP ROLL','SLASH','BACK ROLL'][:len(weights)]:
            raise ValueError('Unsupported authored attack choice order')
        lines.append(f'inline constexpr float {name}[]={{'+floats(weights+[0]*(4-len(weights)))+'};')
    limits=state_action(control,'In Range Double','SendRandomEventV2')['eventMax']['elements']
    lines.append('inline constexpr unsigned repeatMax[]={'+','.join(str(literal(n)) for n in limits)+'};')
    physics = json.loads((directory / 'physics.json').read_text())[0]
    number('gravity', -physics['m_Gravity']['y'] * one(knight,'Rigidbody2D')['m_GravityScale'])
    values = {
        'closeTime': (battle,'Close','Wait','time'),
        'firstTimeout': (battle,'Knight 1','Wait','time'),
        'wakeDelay': (battle,'Pause 1','Wait','time'),
        'victoryPause': (battle,'Pause 5','Wait','time'),
        'musicEndTime': (battle,'Music End','Wait','time'),
        'bugsTime': (control,'Bugs In','Wait','time'),
        'cloudTime': (control,'Cloud Stop','Wait','time'),
        'bugsEndTime': (control,'Bugs In End','Wait','time'),
        'roarTime': (control,'Roar','Wait','time'),
        'roarEndTime': (control,'Roar End','Wait','time'),
        'chargeAnticTime': (control,'Charge Antic','Wait','time'),
        'chargeTimeMin': (control,'Charge Antic','RandomFloat','min'),
        'chargeTimeMax': (control,'Charge Antic','RandomFloat','max'),
        'chargeRecoverTime': (control,'Charge Recover','Wait','time'),
        'chargeDeceleration': (control,'Charge Recover','DecelerateXY','decelerationX'),
        'wallSpeedFactor': (control,'Hit Wall','FloatMultiply','multiplyBy'),
        'wallTimeLoss': (control,'Hit Wall','FloatSubtract','subtract'),
        'jumpAnticSpeed': (control,'Jump Antic','SetVelocity2d','y'),
        'jumpSpeed': (control,'Jump Launch','SetVelocity2d','y'),
        'bounceSpeed': (control,'Bounce','SetVelocity2d','y'),
        'bounceTime': (control,'Bounce','Wait','time'),
        'jumpAimFactor': (control,'Aim','FloatMultiply','multiplyBy'),
        'jumpJitterMin': (control,'Aim','RandomFloat','min'),
        'jumpJitterMax': (control,'Aim','RandomFloat','max'),
        'jumpClampMin': (control,'Aim','FloatClamp','minValue'),
        'jumpClampMax': (control,'Aim','FloatClamp','maxValue'),
        'recoverTime': (control,'Recover','Wait','time'),
        'backRollTime': (control,'Roll','Wait','time'),
    }
    for name, args in values.items(): number(name,param(*args))
    number('idleMin',scalars['Idle Min']); number('idleMax',scalars['Idle Max'])
    # Set Time writes solo values, then group values; preserve authored action order.
    set_time = next(s for s in control['states'] if s['name']=='Set Time')
    times = [literal(a['parameters']['floatValue']) for a in set_time['actions']
             if a['enabled'] and a['type'].split(',')[0].endswith('.SetFloatValue')]
    for name, value in zip(('soloIdleMin','soloIdleMax','groupIdleMin','groupIdleMax'),times):number(name,value)
    rect('body',rectangle(one(knight,'BoxCollider2D')))
    rect('attackRange',rectangle(one(child('Attack Range'),'BoxCollider2D')))
    rect('slashRange',rectangle(one(child('Slash Range'),'BoxCollider2D')))
    for i in (1,2):
        points = one(child(f'Slash{i} Hit'),'PolygonCollider2D')['m_Points']['m_Paths'][0]
        lines.append(f'inline constexpr Vec2 slash{i}[]={{'+','.join('{'+floats((p['x'],p['y']))+'}' for p in points)+'};')
    rect('trigger',rectangle(one(actors['Battle Control'],'BoxCollider2D'),world(go_transform[actors['Battle Control']['path_id']])))
    poses = [world(go_transform[actors[f'Black Knight {i}']['path_id']]) for i in range(1,7)]
    lines.append('inline constexpr Vec2 spawns[]={'+','.join('{'+floats(p[:2])+'}' for p in poses)+'};')
    lines.append('inline constexpr float scales[]={'+floats(p[2] for p in poses)+'};')
    gates=[rectangle(one(actors[name],'BoxCollider2D'),world(go_transform[actors[name]['path_id']])) for name in ('Battle Gate','Battle Gate (1)')]
    lines.append('inline constexpr Rect gates[]={'+','.join('{'+floats(g)+'}' for g in gates)+'};')
    animator=next(c for c in knight['components'] if c['type']=='tk2dSpriteAnimator')
    clips=animator['animation_library']['clips']
    lines.append('struct ClipTime {const char* name;float seconds;};')
    lines.append('inline constexpr ClipTime clips[]={'+','.join('{"'+c['name']+'",'+floats([len(c['frames'])/c['fps']])+'}' for c in clips if c['frames'])+'};')
    lines.append('}')
    return '\n'.join(lines)+'\n'


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input',type=Path,default=Path('_private/minimum-bosses'))
    parser.add_argument('--output',type=Path,default=Path('include/watcher_knights_data.hpp'))
    args=parser.parse_args()
    args.output.write_text(convert(args.input),encoding='utf-8')
