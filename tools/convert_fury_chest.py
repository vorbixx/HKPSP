def tutorial_reveals(mapping, read):
    """UP is broadcast to children; their Delay/Up states own the fades."""
    reveals = []
    for tree in ['469', '494', '459/476', '459/461', '478', '457', '451', '441']:
        node = mapping['trees']['CharmTutorial/' + tree]
        fsms = [read(mapping['fsms'][name]) for name in node['components'] if name in mapping['fsms']]
        fsm = next(f for f in fsms if any(s['name'] == 'Delay' for s in f['states']))
        floats = {v['name']: v['value'] for v in fsm['variables']['floatVariables']}
        colors = {v['name']: v['value'] for v in fsm['variables']['colorVariables']}
        up = next(s for s in fsm['states'] if s['name'] == 'Up')
        ease = next(a['parameters'] for a in up['actions'] if a['type'].endswith('.EaseColor'))
        if ease['easeType'] != 21:  # EaseFsmAction.EaseType.linear, build 22529139.
            raise ValueError('Unsupported Fury tutorial easing')
        reveals.append([floats['Up Delay'], floats['Up Time'], colors['Up Colour']['a']])
    root = read('sharedassets6.assets-1185-fsm.json')
    up = next(s for s in root['states'] if s['name'] == 'Up')
    wait = next(a['parameters']['time']['value'] for a in up['actions'] if a['type'].endswith('.Wait'))
    reveals.append([wait, 0, 1])  # Stop is activated after the root's five-second Wait.
    return reveals


def tutorial_prompt(source=ROOT / '_private/research/fury-reveals-source-20261023'):
    manifest = json.loads((source / 'manifest.json').read_text())
    for name, expected in manifest['source_sha256'].items():
        if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
            raise ValueError('Changed Fury prompt source: ' + name)
    clip = json.loads((source / manifest['clips'][0]).read_text())
    curve = next(c for c in clip['m_FloatCurves'] if c['m_Attribute'] == 'm_Color.a' and not c['m_Path'])
    keys = [[k['m_Time'], k['m_Value'], k['m_InSlope'], k['m_OutSlope']] for k in curve['m_Curve']['m_Curve']]
    settings = clip['m_MuscleClip']
    if not settings['m_LoopTime'] or settings['m_StartTime'] != 0 or settings['m_StopTime'] != keys[-1][0]:
        raise ValueError('Unsupported Fury prompt loop interval')
    if any(k['m_WeightedMode'] for k in curve['m_Curve']['m_Curve']):
        raise ValueError('Unsupported weighted Fury prompt curve')
    return dict(keys=keys, source_sha256=manifest['source_sha256'])


def tutorial_header(reveals, rows, prompt):
    text = ('// Generated by tools/convert_fury_chest.py from build 22529139.\n'
            '#pragma once\n#include <array>\nnamespace hk3ds::furytutorialdata {\n'
            'struct Reveal { float delay, duration, alpha; };\n'
            'inline constexpr std::array<Reveal,9> reveals{{\n')
    text += ''.join('    {' + ','.join(f'{v:.9f}f' for v in row) + '},\n' for row in reveals)
    text += '}};\ninline constexpr std::array<unsigned,' + str(len(rows)) + '> rows{{'
    text += ','.join(map(str, rows)) + '}};\n'
    text += 'struct Key { float time, value, inSlope, outSlope; };\n'
    text += 'inline constexpr std::array<Key,' + str(len(prompt['keys'])) + '> prompt{{\n'
    text += ''.join('    {' + ','.join(f'{v:.9f}f' for v in row) + '},\n' for row in prompt['keys'])
    return text + '}};\n}\n'


def particle_config(mapping, read, tree, system, chain=None):
    """Source emitter placement, ranges and sampled Hermite size curve."""
    chain = [] if chain is None else chain
    node = tree
    while node:
        chain.append(read(mapping['trees'][node]['components'][0]))
        node = node.rsplit('/', 1)[0] if '/' in node else ''
    origin = project((0, 0, 0), chain)
    axes = [tuple(a-b for a, b in zip(project(v, chain), origin))
            for v in [(1, 0, 0), (0, 1, 0)]]
    source = read(system)
    initial, shape = source['m_InitialModule'], source['m_ShapeModule']
    force = source['m_ForceModule']
    clamp = source['m_ClampVelocityModule']
    values = [*origin, *axes[0], *axes[1], math.radians(shape['m_ArcParameter']['m_Value']),
              shape['m_RadiusParameter']['m_Value'],
              limits(source['m_EmissionModule']['m_RateOverTime'])[0],
              0 if source['m_Looping'] else source['m_LengthInSec'],
              *limits(initial['m_StartLifetime']), *limits(initial['m_StartSize']),
              *limits(initial['m_StartSpeed']),
              *(limits(force['m_Y']) if force['m_Enabled'] else (0, 0)),
              limits(clamp['m_Magnitude'])[0] if clamp['m_Enabled'] else 0,
              clamp['m_Dampen'] if clamp['m_Enabled'] else 0,
              initial['m_StartColor']['m_MaxColor']['m_A']]
    values += [limits(source['m_SizeModule']['m_Curve'], i/31)[0] for i in range(32)]
    if len(values) != 56 or source['m_CollisionModule']['m_Enabled']:
        raise ValueError('Unsupported Fury emitter')
    return values


def convert(source, output, romfs, tex3ds):
    for p in (output, romfs):
        if not p.absolute().is_relative_to(ROOT / '_private'):
            raise ValueError('Original resources must remain private')
        p.mkdir(parents=True, exist_ok=True)
    mapping = json.loads((source / 'fury-chest-map.json').read_text())
    for name, expected in mapping['source_sha256'].items():
        if hashlib.sha256((source / name).read_bytes()).hexdigest() != expected:
            raise ValueError('Changed Fury source: ' + name)
    extra = ROOT / '_private/research/fury-presentation-source-20261022'
    extra_map = json.loads((extra / 'fury-presentation-map.json').read_text())
    for name, expected in extra_map['source_sha256'].items():
        if hashlib.sha256((extra / name).read_bytes()).hexdigest() != expected:
            raise ValueError('Changed Fury presentation source: ' + name)
    def extra_read(name):
        return json.loads((extra / name).read_text())
    def extra_ref(name, field):
        return extra_map['visual_assets'][name]['references'][field]
    def extra_texture(name):
        return Image.open(extra / extra_map['visual_assets'][name]['png']).convert('RGBA')

    def read(name):
        return json.loads((source / name).read_text())

    def ref(name, key):
        return mapping['visual_assets'][name]['references'][key]

    def texture(name):
        return Image.open(source / mapping['visual_assets'][name]['png']).convert('RGBA')

    def native(name):
        return decode_native_sprite(texture(ref(name, 'm_RD/m_Texture')), read(name))

    def tk2d(collection, sprite_id):
        data = read(collection)['m_Structure']
        atlas = texture(ref(collection, 'textures/0'))
        return decode_sprite(atlas, data['spriteDefinitions'][sprite_id])

    sprites, clips = {}, []

    def add_sprite(key, decoded, tint=(1, 1, 1, 1), half=True):
        if key not in sprites:
            bitmap, geometry = decoded
            if half:
                bitmap = bitmap.convert('RGBa').resize((max(1, (bitmap.width+1)//2), max(1, (bitmap.height+1)//2)), Image.Resampling.BOX).convert('RGBA')
            for channel, gain in enumerate(tint):
                if gain != 1:
                    channels = list(bitmap.split())
                    channels[channel] = channels[channel].point(lambda x: round(x*gain))
                    bitmap = Image.merge('RGBA', channels)
            sprites[key] = (bitmap, geometry)
        return key

    def clip(name, keys, fps=1, wrap=0, loop=0):
        clips.append(dict(name=name, keys=keys, fps=fps, wrap=wrap, loop=loop))

    library_name = ref('level6-11976.json', 'library')
    library = read(library_name)['m_Structure']['clips']
    chest_tint = read('level6-11920.json')['m_Structure']['_color']
    tint = tuple(chest_tint[k] for k in ('r', 'g', 'b', 'a'))
    for c in library:
        keys = []
        for frame in c['frames']:
            collection = ref(library_name, f'clip/{c["name"]}/{frame["spriteId"]}')
            key = f'chest/{frame["spriteId"]}'
            decoded = tk2d(collection, frame['spriteId'])
            if c['name'] == 'Burst':
                # Approximation: the short burst uses the same screen-resolution
                # reduction as the pickup flash, retaining source world bounds.
                image, geometry = decoded
                decoded = (image.convert('RGBa').resize((math.ceil(image.width/4), math.ceil(image.height/4)), Image.Resampling.BOX).convert('RGBA'), geometry)
            keys.append(add_sprite(key, decoded, tint if c['name'] != 'Burst' else (1, 1, 1, 1), half=c['name'] != 'Burst'))
        clip('Fury ' + c['name'], keys, c['fps'], c['wrapMode'], c['loopStart'])
    event_frames = [i for i, f in enumerate(next(c for c in library if c['name'] == 'Open')['frames']) if f['triggerEvent']]
    if event_frames != [1]:
        raise ValueError('Chest Open spawn event changed')
    for name, component in [('Back', 'level6-11922.json'), ('Front', 'level6-11919.json')]:
        data = read(component)['m_Structure']
        key = add_sprite(name, tk2d(ref(component, 'collection'), data['_spriteId']))
        clip('Fury ' + name, [key])
    animation = mapping['shiny_animation']
    shiny_keys = []
    for i, frame in enumerate(animation['frames']):
        if abs(frame['time'] - i/animation['fps']) > 1e-5:
            raise ValueError('Shiny sprite curve is not uniformly sampled')
        shiny_keys.append(add_sprite('Shiny/' + str(i), native(frame['sprite'])))
    clip('Fury Shiny', shiny_keys, animation['fps'], 0 if animation['loop'] else 2)
    for name, component in [('Glow', 'level6-11866.json'),
                            ('Wave', 'level6-11868.json')]:
        color = read(component)['m_Color']
        # Shiny Sprite is an invisible helper (alpha zero), not an idle halo.
        key = add_sprite(name, native(ref(component, 'm_Sprite')),
                         tuple(color['m_' + c] for c in 'RGBA'))
        clip('Fury ' + name, [key])

    emitters = []
    for name, tree, system, renderer in [
            ('Idle', 'Chest/1757', 'level6-8580.json', 'level6-8766.json'),
            ('Ring', 'Chest/1765/1761', 'level6-8579.json', 'level6-8765.json'),
            ('Trail', 'Chest/1763/2549/2547', 'level6-8596.json', 'level6-8782.json')]:
        material = ref(renderer, 'm_Materials/0')
        image = texture(ref(material, 'm_SavedProperties/m_TexEnvs/_MainTex/m_Texture'))
        # Particle billboards have unit geometry; source startSize is their diameter.
        key = add_sprite('Particle/' + name, (image, (-.5, -.5, .5, .5)), half=False)
        clip('Fury Particle ' + name, [key])
        emitters.append(particle_config(mapping, read, tree, system))

    flash_root = extra_read('resources.assets-9607.json')
    flash_root['m_LocalPosition'] = dict(m_X=0, m_Y=0, m_Z=0)
    flash_emitter = particle_config(extra_map, extra_read, '', 'resources.assets-14616.json', [flash_root])
    emitters.append(flash_emitter)
    clip('Fury Particle Flash', ['Particle/Trail'])
    for name, animation in [('Strike', 'Sword'), ('Tink', 'Block')]:
        animator = 'resources.assets-21845.json' if name == 'Strike' else 'resources.assets-24232.json'
        library_name = extra_ref(animator, 'library')
        c = next(c for c in extra_read(library_name)['m_Structure']['clips'] if c['name'] == animation)
        keys = []
        scale = 1 if name == 'Strike' else 1.5
        for frame in c['frames']:
            collection = extra_ref(animator, f'clip/{animation}/{frame["spriteId"]}')
            data = extra_read(collection)['m_Structure']
            atlas = extra_texture(extra_ref(collection, 'textures/0'))
            image, geometry = decode_sprite(atlas, data['spriteDefinitions'][frame['spriteId']])
            # Approximation: short effects use quarter-resolution source art;
            # authored bounds stay intact and still oversample the 400x240 screen.
            image = image.convert('RGBa').resize((math.ceil(image.width/4), math.ceil(image.height/4)), Image.Resampling.BOX).convert('RGBA')
            keys.append(add_sprite(name+'/'+str(frame['spriteId']), (image, tuple(x*scale for x in geometry)), half=False))
        clip('Fury '+name, keys, c['fps'], c['wrapMode'], c['loopStart'])
    flash_keys = []
    for frame in extra_map['groups']['pickup_burst']['frames']:
        sprite = frame['sprite']
        image, geometry = decode_native_sprite(extra_texture(extra_ref(sprite, 'm_RD/m_Texture')), extra_read(sprite))
        image = image.convert('RGBa').resize((math.ceil(image.width/4), math.ceil(image.height/4)), Image.Resampling.BOX).convert('RGBA')
        flash_keys.append(add_sprite('Flash/'+sprite, (image, tuple(x*1.2*1.15 for x in geometry)), half=False))
    clip('Fury Flash', flash_keys, 20, 2)

    # Reflow the source tutorial for the 320x240 LCD, retaining its hierarchy.
    prompts_path = ROOT / '_private/research/tutorial-reminders/EN_Prompts-decrypted.xml'
    prompts = {entry.attrib['name']: entry.text for entry in ET.parse(prompts_path).getroot()}
    message = {key: prompts[key] for key in ['CHARM_TUTE_TITLE', 'CHARM_TUTE_SUB', 'CHARM_REMINDER']}
    icon, _ = native(mapping['fury_icon']['sprite'])
    font_bytes = (source / 'Perpetua.ttf').read_bytes()
    title_font = ImageFont.truetype(io.BytesIO(font_bytes), 21)
    small_font = ImageFont.truetype(io.BytesIO(font_bytes), 14)
    interactions = append_interactions(add_sprite, clip, output, romfs)
    # Pack separate rows/art rather than an empty panel: no extra texture page.
    draw = ImageDraw.Draw(Image.new('RGBA', (1, 1)))
    message_lines, message_groups = [], []
    reveals = tutorial_reveals(mapping, read)
    prompt_curve = tutorial_prompt()
    def placed(key, bitmap, x, y):
        # Discard only zero-alpha padding; retain the exact visible placement.
        bounds = bitmap.getchannel('A').getbbox()
        if not bounds:
            raise ValueError('Empty Fury tutorial artwork: ' + key)
        left, top, right, bottom = bounds
        geometry = (x-160-bitmap.width/2+left, 126-y-bottom,
                    x-160-bitmap.width/2+right, 126-y-top)
        bitmap = bitmap.crop(bounds)
        if key.startswith('Message/'):
            bitmap, geometry = lcd_text(bitmap, geometry, ppu=1)
        return add_sprite(key, (bitmap, geometry), half=False)

    def message_line(text, y, font, x=160, group=1):
        width = math.ceil(draw.textlength(text, font=font))+4
        bitmap = Image.new('RGBA', (width, 27 if font is title_font else 19))
        ImageDraw.Draw(bitmap).text((width/2, 0), text, anchor='mt', font=font, fill='white')
        key = placed('Message/' + str(len(message_lines)), bitmap, x, y)
        clip('Fury Message ' + str(len(message_lines)), [key])
        message_lines.append(text)
        message_groups.append(group)
    message_line(message['CHARM_TUTE_TITLE'], 25, title_font)
    tutorial_art = {'Divider': ref('sharedassets6.assets-993.json', 'm_Sprite'),
                    'Illustration': ref('sharedassets6.assets-995.json', 'm_Sprite')}
    for name, size, y in [('Divider', (240, 14), 43), ('Illustration', (90, 67), 106)]:
        bitmap, _ = native(tutorial_art[name])
        bitmap = bitmap.convert('RGBa')
        bitmap.thumbnail(size, Image.Resampling.LANCZOS)
        clip('Fury ' + name, [placed(name, bitmap.convert('RGBA'), 160, y)])
    icon.thumbnail((24, 24), Image.Resampling.LANCZOS)
    name = 'Fury of the Fallen'
    name_width = draw.textlength(name, font=title_font)
    group_left = 160-(icon.width+8+name_width)/2
    key = placed('Icon', icon, group_left+icon.width/2, 58)
    clip('Fury Icon', [key])
    message_line(name, 62, title_font, group_left+icon.width+8+name_width/2, group=3)
    def paragraph(text, y, width=274, group=5):
        lines, line = [], ''
        for word in text.split():
            candidate = (line + ' ' + word).strip()
            if draw.textlength(candidate, font=small_font) > width:
                lines.append(line)
                line = word
            else:
                line = candidate
        lines.append(line)
        for line in lines:
            message_line(line, y, small_font, group=group)
            y += 18
        return y
    paragraph(message['CHARM_TUTE_SUB'], 87)
    y = paragraph(message['CHARM_REMINDER'], 181, 254, group=6)
    if y > 217:
        raise ValueError('Full source item message exceeds the bottom screen')
    message_line('A / B / X / Y', 217, small_font, group=8)
    if len(message_lines)>8:
        raise ValueError('Message row capacity exceeded')

    def transform(tree):
        chain = []
        while tree:
            node = mapping['trees'][tree]
            t = read(node['components'][0])
            if tree == 'Chest/1765/1761':
                # Billboard ring: its 3D emitter rotation is not a quad rotation.
                t['m_LocalRotation'] = dict(m_X=0, m_Y=0, m_Z=0, m_W=1)
            chain.append(t)
            tree = tree.rsplit('/', 1)[0] if '/' in tree else ''
        return world_transform(chain)

    trees = ['Chest', 'Chest/1758/1762', 'Chest/1758/1760', 'Chest/1765/1764',
             'Chest/1763/2549/2548', 'Chest/1763/2549', 'Chest/3807', 'Chest']
    values = []
    for tree in trees:
        pos, scale = transform(tree)
        if tree == 'Chest/1763/2549/2548':
            # WaveEffectControl replaces the child's local scale every Update.
            # Retain its parent's scale, including the shiny's authored 1.5.
            _, scale = transform('Chest/1763/2549')
        values.extend((*pos, *scale[:2]))

    def box(name, tree):
        data = read(name)
        pos, scale = transform(tree)
        x = pos[0] + data['m_Offset']['m_X']*scale[0]
        y = pos[1] + data['m_Offset']['m_Y']*scale[1]
        w = data['m_Size']['m_X']*abs(scale[0])/2
        h = data['m_Size']['m_Y']*abs(scale[1])/2
        return [x-w, y-h, x+w, y+h]

    nail_bounds = box('level6-8214.json', 'Chest')
    # Range? also accepts a missing Hero Region. This chest has no such child;
    # therefore nail overlap alone is sufficient, despite Hero Range=false.
    hero_range = nail_bounds
    inspect_range = box('level6-8270.json', 'Chest/1763/2549/2550')
    values.extend((*nail_bounds, *hero_range, *inspect_range, 1/12))
    opened_sides = [box('level6-8215.json', 'Chest/1758'), box('level6-8216.json', 'Chest/1758')]
    range_required = any(n['name'] == 'Hero Region' for n in mapping['trees'].values())
    values.extend(x for b in opened_sides for x in b)
    states = {s['name']: s for s in read('level6-12202-fsm.json')['states']}
    def action(state, name):
        return next(a['parameters'] for a in states[state]['actions']
                    if a['enabled'] and a['type'].split('.')[-1] == name)
    gravity_path = ROOT / '_private/research/assets/Physics2DSettings.json'
    gravity = json.loads(gravity_path.read_text())['m_Gravity']['m_Y']
    gravity *= action('Fling?', 'SetGravity2dScale')['gravityScale']['value']
    shiny_pos, _ = transform('Chest/1763/2549')
    bounds = box('level6-8271.json', 'Chest/1763/2549')
    motion = [bounds[0]-shiny_pos[0], bounds[1]-shiny_pos[1],
              bounds[2]-shiny_pos[0], bounds[3]-shiny_pos[1], gravity]
    for state in ('Fling R', 'Fling L'):
        fling = action(state, 'FlingObject')
        if fling['speedMin'] != fling['speedMax']:
            raise ValueError('Unsupported shiny fling speed range')
        motion.extend(fling[k]['value'] for k in ('speedMin', 'angleMin', 'angleMax'))
    bounce = read('level6-12899.json')['m_Structure']
    motion.extend((bounce['bounceFactor'], bounce['speedThreshold']))
    (output / 'fury-chest.bin').write_bytes(struct.pack('<4s61fI237f', b'FCH3', *values, int(range_required),
                                                       *(v for emitter in emitters for v in emitter), *motion))
    # All source sprites, including tink/inspection, fit this lossless page.
    # Keep the allocation fixed so future additions must pass admission again.
    records,pages,formats = mixed_pages([(k,*v) for k,v in sprites.items()],
                                        [(512,256),(256,256),(256,128)], [(512,128)])
    allocation = texture_bytes(pages, formats)
    if allocation > 1024*1024:
        raise ValueError('Fury text exceeds its existing 1 MiB texture budget')
    ids = sorted(sprites)
    with (output / 'fury-visual.bin').open('wb') as f:
        f.write(struct.pack('<4s4I', b'HKA1', len(pages), len(ids), len(clips), sum(len(c['keys']) for c in clips)))
        for key in ids:
            f.write(struct.pack('<5I4f', *records[key]))
        first = 0
        for c in clips:
            f.write(struct.pack('<48sf4I', c['name'].encode(), c['fps'], c['wrap'], c['loop'], first, len(c['keys'])))
            first += len(c['keys'])
        for c in clips:
            for key in c['keys']:
                f.write(struct.pack('<I', ids.index(key)))
    for i,page in enumerate(pages):
        page.save(output / f'fury-page-{i}.png')
        tex3ds_cache.run([str(tex3ds), '-f', formats[i], '-z', 'none', '-o', str(output / f'fury-page-{i}.t3x'), str(output / f'fury-page-{i}.png')], check=True)
    page_names = {f'fury-page-{i}{suffix}' for i in range(len(pages)) for suffix in ('.png', '.t3x')}
    for name in ('fury-visual.bin', 'fury-chest.bin', *(f'fury-page-{i}.t3x' for i in range(len(pages)))):
        shutil.copyfile(output / name, romfs / name)
    # Regeneration must also remove the previous allocation from the package.
    for directory in (output, romfs):
        for path in directory.glob('fury-page-*'):
            if path.suffix in ('.png', '.t3x') and path.name not in page_names:
                path.unlink()
    manifest = dict(build=mapping['build'], source_sha256=mapping['source_sha256'], pages=len(pages),
                    texture_bytes=allocation, texture_formats=formats, page_sizes=[list(p.size) for p in pages], clips=clips,
                    records=records, interactions=interactions, nail_bounds=nail_bounds, hero_range=hero_range, inspect_range=inspect_range,
                    spawn_seconds=1/12, range_required=range_required, opened_sides=opened_sides, parts=values[:40],
                    emitters=emitters, message=message, message_lines=message_lines, tutorial_art=tutorial_art,
                    tutorial_reveals=reveals, message_groups=message_groups, tutorial_prompt=prompt_curve,
                    message_font_pixels=[21, 21]+[14]*(len(message_lines)-2),
                    shiny_motion=motion, physics_source_sha256=hashlib.sha256(gravity_path.read_bytes()).hexdigest(),
                    message_source_sha256=hashlib.sha256(prompts_path.read_bytes()).hexdigest())
    manifest['presentation_source_sha256'] = extra_map['source_sha256']
    header = ROOT / 'include/fury_tutorial_data.hpp'
    generated = tutorial_header(reveals, message_groups, prompt_curve)
    if not header.exists() or header.read_text() != generated:
        header.write_text(generated, encoding='utf-8', newline='\n')
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2))
    print(json.dumps(dict(sprites=len(ids), pages=len(pages), texture_bytes=manifest['texture_bytes'])))
    return manifest


