"""Extract Monomon's hit/focus rules from level402 actor84 Control."""
import converted_files
import argparse
import json
from pathlib import Path
from convert_uumuu_quirrel import one, state


def extract(source):
    actor = one([a for a in source['actors'] if a['path_id'] == 84], 'Monomon actor84')
    control = one([c['decoded'] for c in actor['components'] if c['type'] == 'PlayMakerFSM'
                   and c['decoded']['name'] == 'Control'], 'Control')
    hits = one([v['value'] for v in control['variables']['intVariables'] if v['name'] == 'Hits'], 'Hits')

    # These actions run together on entry: Wait does not delay IntAdd.
    # A sequenced source revision needs a different runtime controller.
    for name in ('Check Hit', 'Suck Pause', 'Sucking', 'Flashing', 'End Ready', 'End Start'):
        if state(control, name)['isSequence'] != 0:
            raise ValueError(f'{name} no longer runs its actions in parallel')
    kinds = [a['type'].split('.')[-1] for a in state(control, 'Check Hit')['actions'] if a['enabled']]
    if kinds != ['Tk2dPlayAnimation', 'Wait', 'SendEventByName', 'Tk2dPlayFrame', 'IntAdd', 'IntCompare']:
        raise ValueError('Unsupported Check Hit action order')

    def action(name, kind):
        return one([a['parameters'] for a in state(control, name)['actions'] if a['enabled']
                    and a['type'].split('.')[-1] == kind], f'{name}/{kind}')

    def wait(name):
        p = action(name, 'Wait')
        if p['realTime'] or p['time'].get('useVariable'):
            raise ValueError(f'{name} must use scaled constant time')
        return p['time']['value']

    decrement = action('Check Hit', 'IntAdd')
    compare = action('Check Hit', 'IntCompare')
    drain = action('End Ready', 'FloatCompare')
    if (decrement['intVariable'] != {'variable': 'Hits'} or decrement['add']['value'] != -1
            or compare['integer2']['value'] != 0 or compare['equal'] != 'WOUND'
            or drain['float1'] != {'variable': 'Suck Timer'} or drain['equal']
            or drain['greaterThan'] != 'END' or drain['tolerance']['value'] != 0):
        raise ValueError('Unsupported original Monomon hit/focus branches')
    for name, event, target in [('End Start', 'FINISHED', 'PlayerData'),
                                ('Cinematic', 'CINEMATIC END', 'Which Mask?')]:
        edges = [(t['fsmEvent']['name'], t['toState']) for t in state(control, name)['transitions']]
        if edges != [(event, target)]:
            raise ValueError('Unsupported Monomon reward/cinematic order')
    glow = one([a for a in source['actors'] if a['path_id'] == 86], 'Wounded actor86')
    transform = one([c['data'] for c in glow['components'] if c['type'] == 'Transform'], 'glow transform')
    fade = one([c['decoded'] for c in glow['components'] if c['type'] == 'PlayMakerFSM'], 'glow fade')
    floats = {v['name']: v['value'] for v in fade['variables']['floatVariables']}
    colors = {v['name']: v['value'] for v in fade['variables']['colorVariables']}
    return dict(hits=hits, hitPause=wait('Check Hit'), suckPause=wait('Suck Pause'),
                sucking=wait('Sucking'), flashing=wait('Flashing'), drain=drain['float2']['value'],
                ending=wait('End Start'), doorPause=wait('Door Scene Pause'),
                glowX=transform['m_LocalPosition']['x'], glowY=transform['m_LocalPosition']['y'],
                glowScale=transform['m_LocalScale']['x'], glowUp=floats['Up Time'],
                glowAlpha=colors['Up Colour']['a'])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', type=Path, default=Path('_private/minimum-bosses/uumuu/level402-source.json'))
    p.add_argument('--header', type=Path, default=Path('include/monomon_data.hpp'))
    args = p.parse_args()
    values = extract(json.loads(args.source.read_text(encoding='utf-8')))
    lines = ['#pragma once', '// Generated by tools/convert_monomon.py; build22529139 level402 actor84 Control.',
             'namespace hk3ds::monomon_data {']
    for name, value in values.items():
        literal = str(value) if name == 'hits' else repr(float(value)) + 'f'
        lines.append(f'inline constexpr {"unsigned" if name == "hits" else "float"} {name} = {literal};')
    args.header.write_text('\n'.join(lines + ['}', '']), encoding='utf-8', newline='\n')
    archive = json.loads(args.source.with_name('level228-source.json').read_text(encoding='utf-8'))
    actors = {a['path_id']: a for a in archive['actors']}
    def component(a, kind):
        return one([c for c in a['components'] if c['type'] == kind], kind)
    def box(a):
        t = component(a, 'Transform')['data']['m_LocalPosition']
        c = component(a, 'BoxCollider2D')['data']
        x, y = t['x']+c['m_Offset']['x'], t['y']+c['m_Offset']['y']
        w, h = c['m_Size']['x']/2, c['m_Size']['y']/2
        return x-w, y-h, x+w, y+h
    def vector(name, value):
        return f'inline constexpr Vec2 {name} = {{{value[0]}f,{value[1]}f}};'
    def rectangle(name, value):
        return f'inline constexpr Rect {name} = {{{",".join(str(float(v))+"f" for v in value)}}};'
    root = component(actors[1615], 'Transform')['data']['m_LocalPosition']
    extra = ['#pragma once', '#include "physics.hpp"', 'namespace hk3ds::monomon_admission_data {']
    for name, actor_id in [('body',1608),('quirrel',1607),('wounded',1610),('mask',1605)]:
        t = component(actors[actor_id], 'Transform')['data']
        p = t['m_LocalPosition']
        extra.append(vector(name, (root['x']+p['x'],root['y']+p['y'])))
        extra.append(f'inline constexpr float {name}Scale = {float(t["m_LocalScale"]["x"])}f;')
    extra.append(rectangle('dreamBox', box(actors[1107])))
    inspect = box(actors[1613])
    extra.append(rectangle('inspectBox', (inspect[0]+root['x'],inspect[1]+root['y'],inspect[2]+root['x'],inspect[3]+root['y'])))
    guardian_actors = json.loads(args.source.read_text())['actors']
    extra.append(rectangle('guardianBox', box(one([a for a in guardian_actors if a['path_id']==84], 'guardian'))))
    orb = one([a for a in guardian_actors if a['name']=='Dreamer Appear orb'], 'appear orb')
    transform = component(orb, 'Transform')['data']
    collider = component(orb, 'BoxCollider2D')['data']
    if transform['m_Father']['m_PathID'] or not collider['m_IsTrigger'] or not collider['m_Enabled']:
        raise ValueError('Unsupported appear orb transform/trigger')
    position, scale, offset, size = (transform['m_LocalPosition'], transform['m_LocalScale'],
                                    collider['m_Offset'], collider['m_Size'])
    bounds = tuple(position[axis]+(offset[axis]+sign*size[axis]/2)*scale[axis]
                   for sign in (-1, 1) for axis in ('x', 'y'))
    extra.append(f'inline constexpr unsigned appearOrbOwner = {orb["path_id"]};')
    orb_owners, orb_transforms = {orb['path_id']}, {component(orb, 'Transform')['path_id']}
    while True:
        children = [a for a in guardian_actors if a['path_id'] not in orb_owners
                    and component(a, 'Transform')['data']['m_Father']['m_PathID'] in orb_transforms]
        if not children:
            break
        orb_owners.update(a['path_id'] for a in children)
        orb_transforms.update(component(a, 'Transform')['path_id'] for a in children)
    extra.append('inline constexpr unsigned appearOrbOwners[] = {' +
                 ','.join(str(owner) for owner in sorted(orb_owners)) + '};')
    extra.append(rectangle('appearOrbBox', bounds))
    fade_control = one([c['decoded'] for c in orb['components'] if c['type']=='PlayMakerFSM'], 'orb Fade')
    def orb_action(st, kind):
        return one([a['parameters'] for a in state(fade_control, st)['actions']
                    if a['enabled'] and a['type'].endswith('.'+kind)], kind)
    trigger = orb_action('Init', 'Trigger2dEvent')
    fade = orb_action('Fade', 'iTweenFadeTo')
    if (trigger['trigger'] != 0 or trigger['sendEvent'] != 'ENTER' or
            fade['alpha']['value'] != 0 or fade['easeType'] != 21 or fade['loopType'] != 0 or
            fade['delay']['value'] != 0 or fade['realTime']['value'] or not fade['includeChildren']['value']):
        raise ValueError('Unsupported appear orb trigger/fade')
    for name, value in [('appearOrbPause', orb_action('Pause', 'Wait')['time']['value']),
                        ('appearOrbFade', fade['time']['value'])]:
        extra.append(f'inline constexpr float {name} = {float(value)}f;')
    convo = one([c['decoded'] for c in actors[1607]['components'] if c.get('path_id')==10919], 'conversation')
    for name, st in [('hold','Hold Anim'),('going','Going'),('tendrils','Tendrils Down'),('rise','Monomon Up'),('finish','Finish')]:
        wait = one([a['parameters']['time']['value'] for a in state(convo,st)['actions'] if a['enabled'] and a['type'].endswith('.Wait')], st)
        extra.append(f'inline constexpr float {name} = {float(wait)}f;')
    dream = one([c['decoded'] for c in actors[1107]['components'] if c['path_id']==10842], 'Dream Enter')
    pause = one([a['parameters']['time']['value'] for a in state(dream,'Dream Box Down')['actions'] if a['enabled'] and a['type'].endswith('.Wait')], 'dream pause')
    extra.append(f'inline constexpr float dreamPause = {float(pause)}f;')
    mask_source = json.loads(args.source.with_name('level403-source.json').read_text(encoding='utf-8'))
    mask_actor = one([a for a in mask_source['actors'] if a['path_id'] == 6], 'mask controller')
    mask_control = one([c['decoded'] for c in mask_actor['components']
                        if c['type'] == 'PlayMakerFSM' and c['decoded']['name'] == 'Control'], 'mask Control')
    for name, st in [('maskShakePause', 'Shake Pause'), ('maskShake', 'Shake'), ('maskFade', 'Fade')]:
        wait = one([a['parameters']['time']['value'] for a in state(mask_control, st)['actions']
                    if a['enabled'] and a['type'].endswith('.Wait')], st)
        extra.append(f'inline constexpr float {name} = {float(wait)}f;')
    fade_time = one([a['parameters']['setValue']['value'] for a in state(mask_control, 'Fade')['actions']
                     if a['enabled'] and a['type'].endswith('.SetFsmFloat')], 'mask white fade')
    extra.append(f'inline constexpr float maskWhiteFade = {float(fade_time)}f;')
    (args.header.parent/'monomon_admission_data.hpp').write_text('\n'.join(extra+['}', '']),encoding='utf-8', newline='\n')
    print(json.dumps(values))


if __name__ == '__main__':
    main()
